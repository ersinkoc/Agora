"""Verify section 5 step 6b against a fixture with the hub's default SAN shape.

The fixture is generated by OpenSSL, not by the unimplemented pairing code.
Repository hubcli.rs and Ca::issue_server show the same DNS:localhost-only SAN.
"""
import json
from pathlib import Path
import subprocess
import tempfile


def run(args, work):
    return subprocess.run(["openssl", *args], cwd=work, text=True, capture_output=True, check=False)


with tempfile.TemporaryDirectory(prefix="0632-cert-") as temporary:
    work = Path(temporary)
    for args in [
        ["req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:P-256", "-nodes", "-days", "1",
         "-keyout", "ca.key", "-out", "ca.pem", "-subj", "/CN=review-ca"],
        ["req", "-new", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:P-256", "-nodes",
         "-keyout", "leaf.key", "-out", "leaf.csr", "-subj", "/CN=localhost"],
    ]:
        result = run(args, work)
        assert result.returncode == 0, result.stderr
    (work / "leaf.ext").write_text("subjectAltName=DNS:localhost\nbasicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=serverAuth\n")
    result = run(["x509", "-req", "-in", "leaf.csr", "-CA", "ca.pem", "-CAkey", "ca.key", "-CAcreateserial",
                  "-out", "leaf.pem", "-days", "1", "-extfile", "leaf.ext"], work)
    assert result.returncode == 0, result.stderr
    chain = run(["verify", "-CAfile", "ca.pem", "leaf.pem"], work)
    local = run(["verify", "-CAfile", "ca.pem", "-verify_hostname", "localhost", "leaf.pem"], work)
    lan = run(["verify", "-CAfile", "ca.pem", "-verify_ip", "192.0.2.10", "leaf.pem"], work)
    print(json.dumps({"fixture_SAN": "DNS:localhost", "trusted_CA_chain_exit": chain.returncode,
                      "localhost_name_exit": local.returncode, "LAN_address_name_exit": lan.returncode,
                      "LAN_failure": "IP address mismatch" if "IP address mismatch" in lan.stderr else lan.stderr.strip()}, indent=2))
    assert chain.returncode == local.returncode == 0
    assert lan.returncode != 0 and "IP address mismatch" in lan.stderr
