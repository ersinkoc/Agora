/// The prefix of every registry kind: `registry-<registry id>` (`agora_adapters::registry_convert`).
pub const REGISTRY_PREFIX: &str = "registry-";

/// Whether `name` is the kind of one of the registry manifests compiled into this program (`registry-<file stem>`).
pub fn is_registry_kind_name(name: &str) -> bool {
    name.strip_prefix(REGISTRY_PREFIX).is_some_and(|id| {
        REGISTRY
            .iter()
            .any(|(file, _)| file.strip_suffix(".toml") == Some(id))
    })
}

/// The built-in terminal kind: the user's own shell (`agora_platform::default_shell`), so a fresh node can always start something.
/// It is made at load time, not from a file, because the shell differs per machine; a folder file of this kind replaces it.
pub const SHELL_KIND: &str = "shell";

/// The built-in `shell` manifest for this machine.
pub fn shell_manifest() -> Result<Manifest, String> {
    let program = agora_platform::default_shell()
        .replace('\\', "\\\\")
        .replace('"', "\\\"");
    let text = format!(
        "kind = \"{SHELL_KIND}\"\ndisplay_name = \"Shell\"\nversion = \"1\"\nmin_engine = 1\n[process]\nlaunch = [\"{program}\"]\n"
    );
    Manifest::parse(&text).map_err(|e| e.to_string())
}

/// Where a loaded kind came from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Source {
    /// Compiled into this binary.
    BuiltIn,
    /// A file in the node's manifests folder.
    Folder(PathBuf),
    /// Compiled into this binary from the ACP registry (ADR-0092): untested in Agora.
    Registry,
}

impl Source {
    /// A stable name for messages (`built-in` or `folder`); the sentence around it lives in `locales/`.
    pub fn name(&self) -> &'static str {
        match self {
            Source::BuiltIn => "built-in",
            Source::Folder(_) => "folder",
            Source::Registry => "registry",
        }
    }
}

/// One agent kind the node can offer, and where its manifest came from.
#[derive(Debug, Clone)]
pub struct Loaded {
    pub manifest: Manifest,
    pub source: Source,
}

/// The registry kinds, then the built-in kinds (the shipped files and `shell`), then the folder's, each later one replacing an earlier
/// one of the same kind: one entry per kind, sorted by kind. A registry kind whose registry id is the name of a hand-made kind is left
/// out too. The second value lists each folder file (or, never in a tested build, a built-in one) that could not be read or parsed,
/// with the reason.
pub fn load(dir: &Path) -> (Vec<Loaded>, Vec<(PathBuf, String)>) {
    load_from(REGISTRY, BUILT_IN, dir)
}

/// [`load`] over the given compiled-in lists (the tests pass their own).
fn load_from(
    registry: &[(&str, &str)],
    built_in: &[(&str, &str)],
    dir: &Path,
) -> (Vec<Loaded>, Vec<(PathBuf, String)>) {
    let mut by_kind: BTreeMap<String, Loaded> = BTreeMap::new();
    let mut problems = Vec::new();
    for (name, text) in registry {
        match Manifest::parse(text) {
            Ok(m) => {
                by_kind.insert(
                    m.kind.clone(),
                    Loaded {
                        manifest: m,
                        source: Source::Registry,
                    },
                );
            }
            Err(e) => problems.push((PathBuf::from(name), e.to_string())),
        }
    }
    for (name, text) in built_in {
        match Manifest::parse(text) {
            Ok(m) => {
                by_kind.insert(
                    m.kind.clone(),
                    Loaded {
                        manifest: m,
                        source: Source::BuiltIn,
                    },
                );
            }
            Err(e) => problems.push((PathBuf::from(name), e.to_string())),
        }
    }
    match shell_manifest() {
        Ok(m) => {
            by_kind.insert(
                m.kind.clone(),
                Loaded {
                    manifest: m,
                    source: Source::BuiltIn,
                },
            );
        }
        Err(e) => problems.push((PathBuf::from("shell"), e)),
    }
    if let Ok(rd) = std::fs::read_dir(dir) {
        let mut paths: Vec<PathBuf> = rd
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|x| x == "toml"))
            .collect();
        paths.sort();
        for p in paths {
            match std::fs::read_to_string(&p)
                .map_err(|e| e.to_string())
                .and_then(|s| Manifest::parse(&s).map_err(|e| e.to_string()))
            {
                Ok(m) => {
                    by_kind.insert(
                        m.kind.clone(),
                        Loaded {
                            manifest: m,
                            source: Source::Folder(p),
                        },
                    );
                }
                Err(e) => problems.push((p, e)),
            }
        }
    }
    covered_registry_kinds(&mut by_kind);
    (by_kind.into_values().collect(), problems)
}

/// Drops each registry kind a hand-made kind already covers: one named by its registry id (`antigravity-acp` covers
/// `registry-antigravity-acp`). A hand-made kind of the very same `kind` has replaced it already.
fn covered_registry_kinds(by_kind: &mut BTreeMap<String, Loaded>) {
    let covered: Vec<String> = by_kind
        .iter()
        .filter(|(kind, l)| {
            l.source == Source::Registry
                && kind
                    .strip_prefix(REGISTRY_PREFIX)
                    .and_then(|id| by_kind.get(id))
                    .is_some_and(|other| other.source != Source::Registry)
        })
        .map(|(kind, _)| kind.clone())
        .collect();
    for kind in covered {
        by_kind.remove(&kind);
    }
}

/// The folder files that replace a built-in kind, as `(kind, file)`: the node says so once at start, because a stale copy of a shipped
/// manifest in the folder silently hides what a newer build brings (a missing `[quota]` among them).
pub fn shadowing(loaded: &[Loaded]) -> Vec<(String, PathBuf)> {
    let built_in: Vec<String> = BUILT_IN
        .iter()
        .filter_map(|(_, text)| Manifest::parse(text).ok())
        .map(|m| m.kind)
        .chain([SHELL_KIND.to_string()])
        .collect();
    loaded
        .iter()
        .filter_map(|l| match &l.source {
            Source::Folder(p) if built_in.contains(&l.manifest.kind) => {
                Some((l.manifest.kind.clone(), p.clone()))
            }
            _ => None,
        })
        .collect()
}

/// Whether a kind's program is a package runner (`agora_adapters::registry_convert::PACKAGE_RUNNERS`, the converter's list), so
/// starting it fetches code.
pub fn fetches_at_start(m: &Manifest) -> bool {
    program(m).is_some_and(agora_adapters::registry_convert::is_package_runner)
}

/// The maintainer's answer on #1133 ("startable, but always signed"): a kind loaded from the ACP registry (`from_registry`, its origin:
/// [`Source::Registry`]) that starts through a package runner is started only by a start a person's trusted device signed (a routed
/// `AgentLaunch`, or a helper start the person approved) or from this machine's own control socket, never by a routed unsigned
/// `AgentStart`, whatever `signed_commands` says. A hand-made kind is not affected, whatever its name or program; a registry kind that
/// runs its own program (one the owner installed) is not either.
pub fn needs_signed_start(m: &Manifest, from_registry: bool) -> bool {
    from_registry && fetches_at_start(m)
}

/// The node's policy for the ACP registry's kinds (ADR-0092; the maintainer's answer on #1133): `agents.registry = off` switches them
/// all off on this machine, `agents.registry.deny = registry-a, registry-b` some of them. A kind switched off is neither offered nor
/// started (`node.policy_denied`, rule `registry_off` or `registry_denied`). Applied to kinds of registry origin only (the supervisor
/// and doctor check the origin): hand-made kinds are never affected, whatever their name.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct RegistryPolicy {
    pub off: bool,
    pub deny: std::collections::BTreeSet<String>,
}

impl RegistryPolicy {
    /// Why a kind may not be offered or started here (the rule named in the refusal), or `None` when it may.
    pub fn refusal(&self, kind: &str) -> Option<&'static str> {
        if !kind.starts_with(REGISTRY_PREFIX) {
            None
        } else if self.off {
            Some("registry_off")
        } else if self.deny.contains(kind) {
            Some("registry_denied")
        } else {
            None
        }
    }
}

/// The program the node looks for to tell whether a kind is installed: the L3 adapter's command, the ACP command, or the terminal
/// launch command, whichever the manifest uses (the same order the node starts it in).
pub fn program(m: &Manifest) -> Option<&str> {
    let acp = m.structured.as_ref().and_then(|s| s.acp.as_ref());
    match (&m.adapter, acp) {
        (Some(a), _) => a.command.first(),
        (None, Some(a)) => a.argv.first(),
        (None, None) => m.process.launch.first(),
    }
    .map(String::as_str)
}

